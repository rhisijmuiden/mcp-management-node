"""Generate docs/mcp-tools.md, the MCP tool reference, from the tools the server registers.

Run from the repository root after adding or changing a tool:

    python backend/scripts/gen_mcp_reference.py

The source code is the truth: names, descriptions, scopes, risk levels and parameters all come
from ``mmn.mcp_server`` and ``mmn.services.gateway``. Sections follow the ``# ---- <title>``
comments in ``mcp_server.py``.
"""

from __future__ import annotations

import asyncio
import inspect
import re
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "docs" / "mcp-tools.md"

SECTION_TITLES = {
    "system": "App: version and updates",
    "backups": "App: backups",
    "mail": "App: mail server",
    "audit": "App: audit log",
    "environments and nodes": "Customers and Proxmox nodes",
    "server administration on nodes": "Server administration (logs, services, packages, files, commands)",
    "standalone servers + troubleshooting": "Stand-alone servers and troubleshooting",
    "VMs and containers": "VMs and containers",
    "templates and community scripts": "Templates and community scripts",
    "scheduled tasks": "Scheduled tasks",
    "network, firewall, SDN": "Network, firewall and SDN",
    "HA, replication, backup jobs, storage": "Cluster: HA, replication, backup jobs and storage",
    "backup management per customer (phase 11)": "Backups of customers: coverage, restores, Proxmox Backup Server",
    "monitoring": "Monitoring",
    "GitHub deployments": "Deployments from GitHub",
    "UniFi (phase 6)": "UniFi Network and Access",
    "AI gateway: approvals and guardrails": "AI gateway: approvals and guardrails",
    "runbooks (phase 13)": "Runbooks",
    "automatic recovery (phase 14)": "Automatic recovery",
    "uptime and SLA (phase 16)": "Uptime and SLA",
    "tickets and customer portal (phase 17)": "Tickets and customer portal",
    "documentation and password vault (phase 18)": "Documentation and password vault",
    "Microsoft 365 / Entra ID (phase 19)": "Microsoft 365 and Entra ID",
    "certificates, firewall and VPN (phase 20)": "Certificates, firewall and VPN",
    "MCP hub": "MCP hub (tools of other MCP servers appear as `<prefix>__<tool>`)",
}
SKIP_SECTIONS = {"ASGI wiring", "resources: customer context"}
RISK_BADGE = {"read": "🟢 read", "operate": "🔵 operate", "change": "🟠 change", "destructive": "🔴 destructive"}


def sections(source: str) -> list[tuple[int, str]]:
    out = []
    for i, line in enumerate(source.splitlines(), start=1):
        m = re.match(r"^# -{10,}\s+(.+?)\s*$", line)
        if m and m.group(1) not in SKIP_SECTIONS:
            out.append((i, m.group(1)))
    return out


def params(schema: dict) -> str:
    props = schema.get("properties") or {}
    required = set(schema.get("required") or [])
    parts = []
    for name in props:
        parts.append(f"`{name}`" if name in required else f"`{name}`?")
    return ", ".join(parts) or "none"


def esc(s: str) -> str:
    return s.replace("|", "\\|").replace("\n", " ")


async def main() -> int:
    sys.path.insert(0, str(ROOT / "backend"))
    import mmn.mcp_server as server
    from mmn.api.tokens import SCOPES
    from mmn.services import gateway

    source = Path(server.__file__).read_text()
    marks = sections(source)
    schemas = {t.name: t.input_schema for t in await server.mcp.list_tools()}

    grouped: dict[str, list] = {title: [] for _, title in marks}
    for spec in gateway.REGISTRY.values():
        fn = getattr(server, spec.name, None)
        line = inspect.getsourcelines(inspect.unwrap(fn))[1] if fn else 10**9
        title = next((t for ln, t in reversed(marks) if ln <= line), marks[-1][1])
        grouped[title].append((line, spec))

    risks = Counter(s.risk for s in gateway.REGISTRY.values())
    lines = [
        "# MCP tool reference",
        "",
        "<!-- Generated by backend/scripts/gen_mcp_reference.py from the source code. Do not edit by hand. -->",
        "",
        f"Stackpilot's built-in MCP server (`https://<your address>/mcp`, Streamable HTTP) offers "
        f"**{len(gateway.REGISTRY)} tools**: {risks['read']} read, {risks['operate']} operate, "
        f"{risks['change']} change and {risks['destructive']} destructive.",
        "",
        "Every call goes through the same pipeline: the token or OAuth connection must hold the tool's "
        "**scope**, the call must stay inside the token's **customers**, the **policy** for the tool's "
        "**risk level** decides whether it runs, waits for approval or is blocked, and the call is written "
        "to the **AI activity log**. See [features](features.md#ai-gateway) for how policies work.",
        "",
        "## Risk levels",
        "",
        "| Risk | Meaning | Default policy |",
        "| --- | --- | --- |",
        f"| {RISK_BADGE['read']} | Look only: status, logs, lists | Run |",
        f"| {RISK_BADGE['operate']} | Routine and easy to undo: restart, snapshot, refresh | Run |",
        f"| {RISK_BADGE['change']} | Changes settings or creates things | Run |",
        f"| {RISK_BADGE['destructive']} | Commands, updates, deletes, doors | Ask for approval |",
        "",
        "Outside a customer's maintenance window, change and destructive calls ask for approval by default. "
        "A call with `dry_run` set counts as read.",
        "",
        "## Scopes",
        "",
        "Tick these per API token or OAuth connection. A tool marked *app-wide* works on the app itself or "
        "across customers and is refused for a token tied to specific customers.",
        "",
        "| Scope | Allows |",
        "| --- | --- |",
    ]
    lines += [f"| `{k}` | {esc(v)} |" for k, v in SCOPES.items()]
    lines += ["", "## Contents", ""]
    for title, items in grouped.items():
        if items:
            name = SECTION_TITLES.get(title, title)
            anchor = re.sub(r"[^a-z0-9 -]", "", name.lower()).replace(" ", "-")
            lines.append(f"- [{name}](#{anchor}) ({len(items)})")
    lines += ["- [Resources](#resources)", ""]

    for title, items in grouped.items():
        if not items:
            continue
        lines += [f"## {SECTION_TITLES.get(title, title)}", "", "| Tool | Risk | Scope | What it does | Parameters |",
                  "| --- | --- | --- | --- | --- |"]
        for _, s in sorted(items, key=lambda x: x[0]):
            scope = f"`{s.scope}`" + (" · app-wide" if s.all_customers else "")
            lines.append(f"| `{s.name}` | {RISK_BADGE[s.risk]} | {scope} | {esc(s.description)} | "
                         f"{params(schemas.get(s.name, {}))} |")
        lines.append("")

    lines += [
        "## Resources",
        "",
        "| URI | What it holds |",
        "| --- | --- |",
        "| `stackpilot://customers` | Every customer with notes and maintenance window |",
        "| `stackpilot://customers/<id or name>` | One customer's context: notes, contacts, maintenance window, SLA |",
        "",
        "Parameters marked `?` are optional.",
        "",
    ]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT.relative_to(ROOT)} ({len(gateway.REGISTRY)} tools)")
    return 0


if __name__ == "__main__":
    raise SystemExit(asyncio.run(main()))
